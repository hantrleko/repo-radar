export interface SeedItem {
  repo: Repository;
  analysis: EvidenceAnalysis;
  domain: string;
  subcategory: string;
  capability: string;
  modality: string;
}

function makeSeed(params: {
  id: number;
  full_name: string;
  description: string;
  stars: number;
  language: string;
  license: string;
  pushed_at: string;
  topics: string[];
  domain: string;
  subcategory: string;
  capability: string;
  modality: string;
  chinese_purpose: string;
  scenarios: string[];
  satisfied: string[];
  unsatisfied: string[];
  unknown: string[];
  os?: { Windows: string; Linux: string; macOS: string };
  gpu?: string;
  deps: string[];
  snippet: string;
}): SeedItem {
  const [owner, name] = params.full_name.split('/');
  return {
    repo: {
      github_id: params.id,
      full_name: params.full_name,
      owner,
      name,
      description: params.description,
      html_url: `https://github.com/${params.full_name}`,
      stars: params.stars,
      language: params.language,
      license_spdx: params.license,
      pushed_at: params.pushed_at,
      topics: params.topics,
    },
    analysis: {
      repo_github_id: params.id,
      chinese_purpose: params.chinese_purpose,
      scenarios: params.scenarios,
      satisfied_conditions: params.satisfied,
      unsatisfied_conditions: params.unsatisfied,
      unknown_conditions: params.unknown,
      os_compatibility: params.os || { Windows: '支持', Linux: '支持', macOS: '支持' },
      gpu_requirement: params.gpu || '无需',
      external_dependencies: params.deps,
      license_summary: params.license,
      maintenance_status: '活跃',
      evidence_snippets: [params.snippet],
    },
    domain: params.domain,
    subcategory: params.subcategory,
    capability: params.capability,
    modality: params.modality,
  };
}

